"""Evaluate the Isolation Forests on SYNTHETIC windows with injected, labelled anomalies.

Usage:  python -m app.evaluate            (trains if needed, writes models/evaluation.json
                                            and ../docs/ML-EVALUATION.md)
These numbers are measured on synthetic data only and say nothing about real-plant performance.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from .model import MODELS_DIR, THRESHOLD_PERCENTILE, TRAIN_WINDOWS, TrainedModel, load_all, train_all
from .synthetic import ANOMALY_KINDS, SPECS, anomalous_window, normal_window

EVAL_SEED = 2026  # different from the training seed
NORMAL_PER_TYPE = 1000
ANOMALIES_PER_KIND = 200
DOC_PATH = Path(__file__).resolve().parents[2] / "docs" / "ML-EVALUATION.md"


def evaluate_model(model: TrainedModel, seed: int = EVAL_SEED) -> dict:
    rng = np.random.default_rng(seed)
    t = model.machine_type

    def flags(windows: list[dict]) -> tuple[np.ndarray, np.ndarray]:
        X = np.array([model.features_of(w) for w in windows])
        scores, _, combined = model.score_matrix(X)
        return scores > model.threshold, combined

    normal_if, normal_flags = flags([normal_window(t, rng) for _ in range(NORMAL_PER_TYPE)])
    per_kind, per_kind_if = {}, {}
    for kind in ANOMALY_KINDS:
        if_only, combined = flags([anomalous_window(t, kind, rng) for _ in range(ANOMALIES_PER_KIND)])
        per_kind[kind] = round(float(combined.mean()), 3)
        per_kind_if[kind] = round(float(if_only.mean()), 3)

    tp = sum(per_kind[k] * ANOMALIES_PER_KIND for k in ANOMALY_KINDS)
    fp = int(normal_flags.sum())
    fn = len(ANOMALY_KINDS) * ANOMALIES_PER_KIND - tp
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    return {
        "machineType": t, "modelVersion": model.version, "threshold": round(model.threshold, 4),
        "precision": round(precision, 3), "recall": round(recall, 3),
        "falsePositiveRate": round(fp / NORMAL_PER_TYPE, 4), "recallByKind": per_kind,
        "isolationForestOnly": {"recallByKind": per_kind_if, "falsePositiveRate": round(float(normal_if.mean()), 4)},
        "zThreshold": round(model.z_threshold, 2),
        "normalWindows": NORMAL_PER_TYPE, "anomalousWindows": len(ANOMALY_KINDS) * ANOMALIES_PER_KIND,
    }


def write_markdown(results: list[dict], path: Path = DOC_PATH) -> None:
    rows = "\n".join(
        f"| {r['machineType']} | {r['precision']:.3f} | {r['recall']:.3f} | {r['falsePositiveRate']:.3f} | "
        + " | ".join(f"{r['recallByKind'][k]:.2f}" for k in ANOMALY_KINDS) + " |"
        for r in results)
    kinds = " | ".join(ANOMALY_KINDS)
    if_rows = "\n".join(
        f"| {r['machineType']} | {r['isolationForestOnly']['falsePositiveRate']:.3f} | "
        + " | ".join(f"{r['isolationForestOnly']['recallByKind'][k]:.2f}" for k in ANOMALY_KINDS) + " |"
        for r in results)
    text = f"""# ML Evaluation — anomaly detection (SYNTHETIC DATA ONLY)

> **These numbers are measured on synthetic data generated by the same simple noise model the
> models were trained on. They say nothing about performance on a real plant.** Real sensors have
> drift, calibration error, process changes, missing data and failure modes that this generator
> does not contain. Do not quote these figures as real-world accuracy.

Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} by `python -m app.evaluate`.

## Method

- **Model**: scikit-learn `IsolationForest` (200 trees), one per machine type, version `{results[0]['modelVersion'] if results else ''}`.
- **Features** (per sensor, over a 60-minute window at 1-minute resolution): mean, standard deviation, slope.
- **Training data**: {TRAIN_WINDOWS} synthetic *normal* windows per machine type (nominal + Gaussian noise;
  temperatures carry a ±2 % daily cycle). Training seed 42.
- **Decision rule**: a window is a statistical anomaly when the Isolation Forest score exceeds its
  threshold (the {THRESHOLD_PERCENTILE}th percentile of training scores) **or** any feature's |z-score| versus the
  training windows exceeds the {THRESHOLD_PERCENTILE}th percentile of max |z| on training windows. Each check alone
  flags ≈0.5 % of normal windows by design, so the combined false-alarm target is ≈1 %.
- **Why the second check**: Isolation Forest draws its splits inside the training range, so a value
  far *beyond* that range is isolated no faster than the most extreme normal point. Measured on this
  data it detected only a small fraction of sustained level shifts (table below). The range check closes that gap.
- **Test data** (seed {EVAL_SEED}, unseen): {NORMAL_PER_TYPE} normal windows + {ANOMALIES_PER_KIND} windows per injected
  anomaly kind, each on one random sensor:
  `level_shift` (6–12 σ offset), `drift` (ramp to 8–15 σ), `spike` (3 points at 10 σ),
  `stuck` (sensor frozen), `noise_burst` (noise ×4), `small_shift` (0.3–0.8 σ offset — deliberately subtle).
- Labels are known exactly because the anomalies are injected.

## Results

| Machine type | Precision | Recall | False-positive rate | {kinds} |
|---|---|---|---|{'---|' * len(ANOMALY_KINDS)}
{rows}

Columns after the false-positive rate are recall per injected anomaly kind (combined rule).

**Read with care:** recall of 1.00 on the large injected anomalies only shows that 6–15 σ changes are
easy to see in clean synthetic data. The `small_shift` column (0.3–0.8 σ) shows where detection
starts to fail. Precision here is inflated because half of the test windows are anomalous; on a real
plant anomalies are rare, so a ~1 % false-alarm rate per window would produce many false alarms per day
unless windows are aggregated or thresholds raised.

### Isolation Forest alone (for comparison)

| Machine type | False-positive rate | {kinds} |
|---|---|{'---|' * len(ANOMALY_KINDS)}
{if_rows}

## What the score means

- The score measures how *unusual* a window is compared with synthetic normal operation.
  Above the threshold = "statistical anomaly". It is **not** a fault diagnosis and **not** a failure
  prediction; an unusual window can be a harmless process change.
- The API also returns the features furthest from the training distribution (z-scores) to show
  *what* is unusual — this is descriptive, not causal.
- **Failure prediction is not implemented**: it needs labelled failure history from the real plant.

## Before real-world use

Real historian data per machine, a review of feature windows and thresholds with maintenance
engineers, evaluation against labelled real events, and monitoring of false-alarm rates.
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main() -> list[dict]:
    models = load_all() or train_all()
    results = [evaluate_model(models[t]) for t in SPECS if t in models]
    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    (MODELS_DIR / "evaluation.json").write_text(json.dumps({r["machineType"]: r for r in results}, indent=2))
    write_markdown(results)
    for r in results:
        print(f"{r['machineType']:<26} precision={r['precision']:.3f} recall={r['recall']:.3f} fpr={r['falsePositiveRate']:.3f}")
    return results


if __name__ == "__main__":
    main()
